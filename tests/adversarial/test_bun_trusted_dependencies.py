"""The install scripts the static build needs are trusted by name, not by bun's default list.

src/lib/db.ts imports PrismaClient from @prisma/client, and the static build type-checks it.
The client is generated by @prisma/client's own postinstall; no build or deploy script runs
`prisma generate`. bun 1.3.4 (CI, packageManager) runs that postinstall from its default trusted
list; bun 1.4.4 blocks it, so on a fresh node_modules the build failed with "Module
'@prisma/client' has no exported member 'PrismaClient'" and redeploy.sh stopped at the static
build (checked 20 Nov 2026: a clean `bun install --frozen-lockfile` generated the client on 1.3.4,
not on 1.4.4, and did on 1.4.4 once trustedDependencies named it).

Trade-off: CI pins bun 1.3.4, so CI cannot show the 1.4 behaviour itself; this test pins the
condition that makes the build independent of bun's default list.
"""
from pathlib import Path
import json
import re
import unittest


ROOT = Path(__file__).resolve().parents[2]
BUILD_SCRIPTS = (
    "scripts/build_static_export.mjs",
    "workers/billing/scripts/deploy.sh",
    "workers/billing/scripts/redeploy.sh",
)


class BunTrustedDependenciesTests(unittest.TestCase):
    def test_the_prisma_client_the_build_imports_is_generated_on_install(self) -> None:
        db = (ROOT / "src/lib/db.ts").read_text(encoding="utf-8")
        if not re.search(r"from ['\"]@prisma/client['\"]", db):
            self.skipTest("src/lib/db.ts no longer imports @prisma/client")
        generates = any("prisma generate" in (ROOT / p).read_text(encoding="utf-8") for p in BUILD_SCRIPTS)
        if generates:
            self.skipTest("a build script generates the client itself")
        trusted = json.loads((ROOT / "package.json").read_text(encoding="utf-8")).get("trustedDependencies", [])
        for name in ("@prisma/client", "prisma"):
            self.assertIn(name, trusted, f"{name} must be in package.json trustedDependencies: bun 1.4 blocks its install script")


if __name__ == "__main__":
    unittest.main()
